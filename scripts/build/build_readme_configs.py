#!/usr/bin/env python3
"""The measured-configuration block in README's *Install & use* section.

**Why a generated block rather than a written table.** The owner asked for a
recommendation of agent + model + effort so a user does not configure twice.
README is a consumer file that ships with the package, and a hand-written table
of vendor model names in a consumer file is a rotting claim with no forcing
function — this repository has shipped twenty-six releases fixing exactly that
class. Generated with `--check` in CI, the block cannot disagree with the
measurement it is derived from, and every row carries `n`, a date and the skill
version its runs read, so a stale row is visibly stale rather than quietly
wrong.

**What it cannot do, said here because README says it too.** This package
cannot set a user's model. Nine platforms load it as a skill file, Codex reads
`AGENTS.md`, and Kimi and DeepSeek get `prompts/lumi-style-core.md` pasted into
a chat — and on every one of those routes the agent is ALREADY RUNNING, with its
model and effort already fixed, when it reads anything of ours. The route
differs; the timing does not. A first draft said "every platform loads it as a
SKILL", which is wrong for three of the twelve and was caught by a review. The
block tells a person what to configure; nothing here configures anything.

The derivation is `agent_evals.py`'s and is not re-implemented: one tool owns
what a configuration costs, and this only renders its answer for the twelve
platforms README claims.
"""
import argparse
import json
import pathlib
import pathlib as _bs_pathlib  # noqa: E402 — the bootstrap's, see below
import sys
import sys as _bs_sys  # noqa: E402 — the bootstrap's, see below

# --- scripts path bootstrap (canonical; the bootstrap guard enforces this) ---
_SCRIPTS_ROOT = next(p for p in _bs_pathlib.Path(__file__).resolve().parents
                     if p.name == "scripts")
for _sub in ("lib", "render", "check", "build", "ops", ""):
    _p = str(_SCRIPTS_ROOT / _sub) if _sub else str(_SCRIPTS_ROOT)
    if _p not in _bs_sys.path:
        _bs_sys.path.append(_p)
del _bs_pathlib, _bs_sys, _SCRIPTS_ROOT, _sub, _p

import agent_evals  # noqa: E402
import trace_store  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parents[2]
README = ROOT / "README.md"

MARK = "<!-- generated by build_readme_configs.py -->"
END = "<!-- end generated: measured configurations -->"


def load_registry() -> list[dict]:
    return json.loads(
        (ROOT / "adapters" / "platforms.json").read_text(encoding="utf-8")
    )["platforms"]


def rows_for_readme(cells=None, registry=None, notes=None) -> list[str]:
    """-> one markdown row per platform README claims.

    `cells` and `registry` are injectable because the suite writes to a scratch
    trace store (conftest, deliberately) and the real one is therefore EMPTY
    under pytest. A test calling this with no arguments loops over nothing and
    passes without looking — which is what the first version of
    `test_no_row_carries_a_cost_without_its_sample_size` did, in a file whose
    other tests are about exactly that failure.
    """
    if cells is None:
        cells = agent_evals.cells(trace_store.load(),
                                  agent_evals.load_history())
    if registry is None:
        registry = load_registry()
    if notes is None:
        notes = []

    out: list[str] = []
    for entry in registry:
        # ONE SELECTION RULE, `agent_evals.pick()`'s. This function had its own
        # copy of it and dropped both caveats the tool exists to say, in the one
        # file that reaches a user.
        state, best, caveats = agent_evals.pick(entry["id"], cells, registry)
        if best is None:
            # THE TWO ABSENCES STAY DIFFERENT. `not measured here` is a machine
            # away; `cannot be measured here` never will be — an IDE with no
            # command line, or a chat model behind an API. Printing them
            # identically made the platform table read as ten pieces of pending
            # work when only six were, and that lesson is already written into
            # conformance/CONFORMANCE.md.
            out.append(f"| **{entry['name']}** | {state} | — | — | — |")
            continue
        earned = ("—" if best["tasks_earned"] is None
                  else f"{best['tasks_earned']} of {best['tasks_attempted']}")
        # OUTPUT TOKENS FIRST, the ratio second. Over four repeats of one
        # configuration output tokens spread 16.5% and the ratio 32.3% —
        # dividing by a page count the agent chose compounds two movements.
        # Both are printed because a reader comparing agents wants the rate and
        # a reader budgeting one build wants the total.
        cost = (f"{best['output_tokens']:,.0f} out-tok · "
                f"{best['tokens_per_page']:,.0f}/page (n={best['runs']})"
                if best.get("output_tokens") is not None
                else f"{best['tokens_per_page']:,.0f} tok/page (n={best['runs']})")
        # The caveats go BELOW the table, not into the cell. Inlined they made
        # one cell three lines wide and the table unreadable, which is its own
        # way of not saying them. Dropping them is what the review found: the
        # README printed `10,167 tok/page (n=1)` for a cell a five-run cell had
        # beaten on sampling, and said neither thing.
        mark = " †" if caveats else ""
        what = " · ".join(
            f"`{x}`" for x in (best["model"],) if x) + (
            f" · effort `{best['effort']}`" if best["effort"] else "")
        out.append(
            f"| **{entry['name']}** | {what} | {earned} | {cost}{mark} | "
            f"{best['measured']} · skill {best['skill_version']} |")
        for caveat in caveats:
            notes.append(f"† **{entry['name']}** — {caveat}.")
    return out


def block() -> str:
    notes: list[str] = []
    rows = rows_for_readme(notes=notes)
    lines = [
        MARK,
        "",
        "**Which model and effort to run it with — measured, not curated.** "
        "Cells with no measurement say so; none is a guess.",
        "",
        "| Agent | Measured configuration | Tasks earned | Cost | Measured |",
        "|---|---|---|---|---|",
        *rows,
        "",
        *([*notes, ""] if notes else []),
        "**A dash is an absence, never a zero.** In a column headed *Tasks "
        "earned* that distinction is the whole cell: a dash means no round "
        "carrying that configuration has been recorded for the agent, not that "
        "it earned nothing. It is a gap in the measurement.",
        "",
        "**One row per platform, not a league table.** Each row shows that "
        "platform's cheapest measured configuration that names a model; the "
        "rows are in registry order and are not ranked against each other. "
        "Where the numbers ARE ordered — by cost among configurations that "
        "already cleared the gate line, which is not a quality ranking, "
        "because above that line the checks cannot tell two documents apart — "
        "is `conformance/CONFIGURATIONS.md`. `n` is small on purpose: "
        "nothing repeats a run by design, so a single sample cannot separate a "
        "flaky agent from a flaky checker. The full board, its axes and what "
        "is still unmeasured are in `conformance/CONFIGURATIONS.md` and "
        "`conformance/agent-evals.json` in the development repository.",
        "",
        "**This package cannot set your model.** However your agent loads it — "
        "as a skill file, as `AGENTS.md`, or as a prompt you paste — your agent "
        "is already running, with its model and effort already chosen, by the "
        "time it reads any of it. The table tells you what to configure once; "
        "it is not automation, and calling it that would be a promise no code "
        "here can keep.",
        "",
        END,
    ]
    return "\n".join(lines) + "\n"


def splice(text: str, new: str) -> str:
    """-> README with the block replaced, or a hard exit naming what is wrong.

    THE MARKERS MUST BOTH BE THERE. A generator that appends when it cannot
    find its own block writes a second copy on every run, and a generator that
    silently does nothing reports success while changing nothing — the two ways
    this goes wrong, and neither may be quiet.
    """
    if text.count(MARK) != 1 or text.count(END) != 1:
        sys.exit(f"{README} carries {text.count(MARK)} start marker(s) and "
                 f"{text.count(END)} end marker(s); it needs exactly one of "
                 f"each. Nothing was written.")
    head = text.split(MARK, 1)[0]
    tail = text.split(END, 1)[1]
    return head + new.rstrip("\n") + tail


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if README's block is not the derivation")
    args = ap.parse_args(argv)

    text = README.read_text(encoding="utf-8")
    want = splice(text, block())
    if args.check:
        if text != want:
            print("FAIL  README.md's measured-configuration block is not what "
                  "the traces and history derive. Regenerate with "
                  "`python3 scripts/build/build_readme_configs.py`; do not "
                  "hand-edit between the markers.")
            return 1
        print("ok    README.md's measured-configuration block matches")
        return 0
    if text == want:
        print("ok    README.md already matches (nothing written)")
        return 0
    README.write_text(want, encoding="utf-8")
    print("wrote README.md's measured-configuration block")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
