#!/usr/bin/env python3
"""Generate references/page-contracts.md — every rule, grouped by the page it binds.

**The owner's request, and why it is generated.** Her instruction was to gather
the deck's layout rules — cover, closing, agenda — into one place so they stop
being forgotten, and to gather the content-page rules separately. The need is
real and measured: "what a cover must be" is today spread across
`storyline-templates.md`, `design-rules.md` and `SKILL.md`, and that scattering
IS the forgetting mechanism. Five conformance rounds produced covers that broke
a different one of those rules each time.

But a HAND-WRITTEN summary of 175 rules would be the largest prose copy this
package has ever created, and prose copies drifting from their source is its
worst measured defect class — twenty-six releases carry a fix for one. So this
page is generated from `evals/rule-coverage.json`, `--check` in CI, on the
`eval-inventory.md` precedent.

**It carries pointers, never rule prose.** Each row is a quotation, a
`file:line`, the metric that measures it, and whether that metric gates. The
rule still lives in exactly one place; this is the index to it. A reader who
needs the rule follows the citation, and cannot mistake this page for the
authority.

    python3 scripts/build/build_page_contracts.py            # write
    python3 scripts/build/build_page_contracts.py --check    # verify current (CI)
"""
from __future__ import annotations

import argparse
import json
import pathlib
import re

ROOT = next(p for p in pathlib.Path(__file__).resolve().parents
            if (p / "SKILL.md").exists())
REGISTER = ROOT / "evals" / "rule-coverage.json"
OUT = ROOT / "references" / "page-contracts.md"

# The six sections, in the order the owner asked for them: the pages that bookend
# a deck and the one that routes it, then the content pages ON THEIR OWN, then
# what binds every page. Each carries the sentence saying what the section is
# for — those are this file's own words about the grouping, not restated rules.
SECTIONS = (
    ("cover", "The cover",
     "The first page a reader sees, and the one every conformance round broke "
     "differently."),
    ("agenda", "The agenda",
     "The page that routes the parts. It quotes the deck; it never rewrites it."),
    ("opener", "The part openers",
     "The seams. A part opener is a claim, a label, a run line and one "
     "silhouette."),
    ("closing", "The closing page",
     "The last page, set like the cover and asking for the decision."),
    ("content", "The content pages",
     "Gathered separately at the owner's direction: these are the pages the "
     "argument is made on, and they outnumber the other four kinds together."),
    ("all", "Every page",
     "The footer, the palette, the type ladder, the layout vocabulary — what "
     "binds regardless of which page it is."),
)


def rows_for(rules: list[dict], kind: str) -> list[dict]:
    return sorted((r for r in rules if r.get("page_kind") == kind),
                  key=lambda r: (r.get("source", ""), r.get("id", "")))


# A rule about Chinese output states its terms in Chinese, and the repository's
# English-only red line permits that ONLY as rule data in backticks. Wrapping
# the runs rather than the whole sentence keeps the English readable.
CJK = re.compile(r"[\u3400-\u9fff\uf900-\ufaff]+")


def _cell(text: str) -> str:
    """A quotation safe inside a Markdown table cell, CJK marked as data."""
    text = text.replace("|", "\\|").replace("\n", " ").strip()
    return CJK.sub(lambda m: f"`{m.group(0)}`", text)


def render() -> str:
    data = json.loads(REGISTER.read_text(encoding="utf-8"))
    rules = data["rules"]
    measured = sum(1 for r in rules if r.get("metric"))
    gated = sum(1 for r in rules if r.get("gates"))

    out = [
        "# Page contracts — what each kind of page owes",
        "",
        "**GENERATED by `scripts/build/build_page_contracts.py` — do not edit.**",
        "Its source is `evals/rule-coverage.json`; the rules themselves live in",
        "`references/`, and each row cites the one place its rule is written.",
        "This page is an index, never an authority: where it disagrees with the",
        "file it cites, the file wins and this page is stale.",
        "",
        f"**{len(rules)} rules · {measured} measured by a metric · {gated} "
        f"gated · {len(rules) - measured} with no automated check.**",
        "",
        "That last number is the point of the page. A rule with no check is not",
        "a rule an agent will follow, because an agent iterates to the edge of",
        "what it is shown — so these are the rules a human still has to read the",
        "document for. `python3 scripts/check/check_rule_coverage.py` keeps the",
        "register honest; it deliberately does not gate on the count.",
        "",
    ]
    for i, (kind, title, blurb) in enumerate(SECTIONS, start=1):
        picked = rows_for(rules, kind)
        # Every `## N ·` section in references/ declares which principle it
        # serves; `check_repo`'s principle-trace guard requires it, and a
        # generated file is held to the same rule as a written one.
        out += [f"## {i} · {title}", "",
                "*Serves: **P-1**.* — one page's obligations in one place, so "
                f"the brand's own rules are the ones a builder can find. · id "
                f"`PC-{i}`", "",
                blurb, ""]
        if not picked:
            out += ["No rule in the register binds this page kind on its own.",
                    ""]
            continue
        unchecked = sum(1 for r in picked if not r.get("metric"))
        out += [f"{len(picked)} rules, {unchecked} of them unchecked.", "",
                "| Rule | Where it is written | Property | Metric | Gates |",
                "| --- | --- | --- | --- | --- |"]
        for r in picked:
            metric = r.get("metric") or "—"
            gates = "yes" if r.get("gates") else "no"
            # A PER-KIND RULE THAT TOUCHES A SHARED PROPERTY SAYS SO HERE. The
            # ground's tier and the footer's marker are decided for every page
            # and then restated for openers; a contracts page that showed only
            # the per-kind sentence let a reader think it was the whole story.
            prop = (r.get("covers") or "").strip()
            against = (r.get("overrides") or "").strip()
            cell = (f"`{prop}`" + (f" ← `{against}`" if against else "")
                    if prop else "—")
            out.append(f"| {_cell(r.get('gist', ''))} "
                       f"| `{r.get('source', '')}` | {cell} | `{metric}` "
                       f"| {gates} |")
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def _shown(path: pathlib.Path) -> str:
    """The path as a reader wants it, without crashing on one outside the tree.

    `relative_to` RAISES on a path that is not under ROOT, so a run pointed at
    a temp directory died inside a print statement. The message is a courtesy;
    it may not be able to fail.
    """
    try:
        return str(path.relative_to(ROOT))
    except ValueError:
        return str(path)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true",
                    help="verify the tracked render is current (CI)")
    args = ap.parse_args(argv)
    rendered = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != rendered:
            print(f"FAIL  {_shown(OUT)} is stale or missing; "
                  f"re-run without --check")
            return 1
        print(f"ok    {_shown(OUT)} is current")
        return 0
    OUT.write_text(rendered, encoding="utf-8")
    print(f"wrote {_shown(OUT)} ({len(rendered.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
