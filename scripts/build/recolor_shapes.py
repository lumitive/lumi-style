#!/usr/bin/env python3
"""Recolour the vendored McKinsey shapes onto LUMI's light canvas — in the
repository, from the tokens, with a --check that holds the committed library
to its own source.

Until 0.1.532 this tool lived outside the repository (in the owner's review
directory, as `recolor_lumi.py`), the un-recoloured originals were not
vendored, and the 206 SVGs under assets/shapes/ could not be regenerated by
any script a clone carries; nor did any `--check` hold them to the tokens they
claim to follow, which every other vendored asset here has (GAP-017). The
port changes nothing in the mapping: `--check` regenerates every unit into
memory and compares bytes, and the first run of it against the committed
library is the proof that the port IS the tool.

How a colour is mapped (unchanged from the extraction)
  1 Colours are ranked by the value the designer wrote, not by what alpha made
    of it; alpha itself is kept.
  2 Faces (chromatic fills) keep their relative lightness ORDER and are spread
    across LUMI's light ramp, darkest source face to --acc-5.
  3 Edges are polarity-inverted, because they were ink: cold white between
    dark faces (--on-acc); canvas ink (--tx1) on line art.
  4 A hue far from the file's dominant hue, used on few marks, is a highlight
    and takes the acid green as a SURFACE, never text.

Output colours are written as `var(--token, #fallback)`: inside a LUMI
document they follow the palette and its dark override; opened alone they
render from the fallback. The fallbacks come from tokens/design-tokens.json
(palette.light), read at run time — except two, named below, which are the
extraction's own soft-ink values and are kept verbatim because they sit inside
every committed file; moving them is a regeneration decision, and --check is
where that decision becomes visible.

Usage
  recolor_shapes.py            # regenerate assets/shapes/*.svg from assets/shapes/source/
  recolor_shapes.py --check    # CI: the committed library is byte-identical to a regeneration
"""
from __future__ import annotations

import json
import pathlib

# --- scripts path bootstrap (canonical; the bootstrap guard enforces this) ---
import pathlib as _bs_pathlib  # noqa: E402
import re
import sys
import sys as _bs_sys  # noqa: E402
from xml.etree import ElementTree as ET

_SCRIPTS_ROOT = next(p for p in _bs_pathlib.Path(__file__).resolve().parents
                     if p.name == "scripts")
for _sub in ("lib", "render", "check", "build", "ops", ""):
    _p = str(_SCRIPTS_ROOT / _sub) if _sub else str(_SCRIPTS_ROOT)
    if _p not in _bs_sys.path:
        _bs_sys.path.append(_p)
del _bs_pathlib, _bs_sys, _SCRIPTS_ROOT, _sub, _p

from color_math import hex_to_rgb, luma255  # noqa: E402

ROOT = next(p for p in pathlib.Path(__file__).resolve().parents
            if (p / "SKILL.md").exists())
SRC = ROOT / "assets" / "shapes" / "source"
OUT = ROOT / "assets" / "shapes"
TOKENS = ROOT / "tokens" / "design-tokens.json"


def _palette() -> dict[str, str]:
    return json.loads(TOKENS.read_text(encoding="utf-8"))["palette"]["light"]


_P = _palette()
# The light ramp and the brand surfaces, read from the tokens.
RAMP = [("--acc-5", _P["light_ramp_5"]), ("--acc-4", _P["light_ramp_4"]),
        ("--acc-3", _P["light_ramp_3"]), ("--acc-2", _P["light_ramp_2"]),
        ("--acc-1", _P["light_ramp_1"])]
INK = ("--tx1", _P["on_light_ramp_low"])
COLD_WHITE = ("--on-acc", _P["on_accent"])
LIME = ("--lime", _P["lime"])
CANVAS = ("--bg", _P["bg"])
# The two fallbacks that are NOT token values: the extraction wrote them as
# "rgba(43,46,51,.20)/.12 flattened on white", which they are not (the true
# composites are #D5D5D6 and #E6E6E7); they are what 206 committed files
# carry, and the var() wins inside any LUMI document. Kept verbatim.
INK_SOFT = ("--ln1", "#6E7175")
INK_HAIR = ("--ln2", "#9EA0A3")

SVG = "http://www.w3.org/2000/svg"
ET.register_namespace("", SVG)


RGB_RE = re.compile(r"rgb\(\s*([\d.]+)(%?)\s*,\s*([\d.]+)(%?)\s*,\s*([\d.]+)(%?)\s*\)")
GEOM = ("path", "rect", "ellipse", "circle", "polygon", "polyline", "line")
TEXT = ("text", "tspan")


def local(tag):
    return tag.split("}")[-1]


def parse_color(value):
    """'rgb(0,0,254)' / 'rgb(0%,0%,99.6%)' / '#RRGGBB' -> (r,g,b) 0-255, or None."""
    if not value or value in ("none", "transparent"):
        return None
    m = RGB_RE.match(value.strip())
    if m:
        out = []
        for i in (1, 3, 5):
            v = float(m.group(i))
            out.append(round(v * 2.55 if m.group(i + 1) == "%" else v))
        return tuple(max(0, min(255, c)) for c in out)
    if value.startswith("#"):
        try:
            return hex_to_rgb(value)
        except Exception:
            return None
    return None


def chroma(rgb):
    return max(rgb) - min(rgb)


def hue(rgb):
    r, g, b = [c / 255 for c in rgb]
    mx, mn = max(r, g, b), min(r, g, b)
    d = mx - mn
    if d == 0:
        return None
    if mx == r:
        h = ((g - b) / d) % 6
    elif mx == g:
        h = (b - r) / d + 2
    else:
        h = (r - g) / d + 4
    return h * 60


def hue_distance(a, b):
    if a is None or b is None:
        return 0.0
    d = abs(a - b) % 360
    return min(d, 360 - d)


def token(pair):
    return f"var({pair[0]}, {pair[1]})"


def collect(root):
    """[(element, attribute, rgb, effective_rgb, alpha)] for every painted mark."""
    marks = []
    for el in root.iter():
        if local(el.tag) not in GEOM:
            continue
        for attr in ("fill", "stroke"):
            rgb = parse_color(el.get(attr))
            if rgb is None:
                continue
            alpha = 1.0
            for a in (f"{attr}-opacity", "opacity"):
                if el.get(a):
                    try:
                        alpha *= float(el.get(a))
                    except ValueError:
                        pass
            marks.append((el, attr, rgb, rgb, alpha))
    return marks


def build_mapping(marks):
    """effective-rgb -> token pair, decided per file by role and lightness."""
    fills = [m for m in marks if m[1] == "fill"]
    strokes = [m for m in marks if m[1] == "stroke"]
    line_art = len(fills) < max(1, 0.2 * len(strokes))

    chromatic_fills = [m for m in fills if chroma(m[3]) >= 26]
    neutral_fills = [m for m in fills if chroma(m[3]) < 26]

    # the file's dominant hue: the most-painted chromatic fill (or stroke)
    pool = chromatic_fills or [m for m in strokes if chroma(m[3]) >= 26]
    hue_count: dict[int, int] = {}
    for m in pool:
        h = hue(m[3])
        if h is not None:
            hue_count[round(h / 30) * 30] = hue_count.get(round(h / 30) * 30, 0) + 1
    dominant = max(hue_count, key=lambda k: hue_count[k]) if hue_count else None

    mapping = {}

    # 1 faces: preserve lightness order, spread across the ramp (deepest first)
    face_colors = sorted({m[3] for m in chromatic_fills
                          if hue_distance(hue(m[3]), dominant) <= 45},
                         key=luma255)
    if face_colors:
        n = len(face_colors)
        if n == 1:
            mapping[face_colors[0]] = RAMP[1]           # a lone mass: mid accent
        else:
            # darkest source face -> --acc-5. The spread stops at --acc-2 so a
            # face never dissolves into the canvas; a long grey gradient uses
            # the full four steps, a three-face solid uses the top three.
            span = 3 if n <= 3 else 4
            for i, c in enumerate(face_colors):
                mapping[c] = RAMP[round(i * (span - 1) / (n - 1))]

    # 2 highlights. At most ONE hue per file takes the acid green: it is an
    # emphasis device, and a figure with four "emphases" has none. The winner is
    # the hue furthest from the dominant among those on a minority of marks;
    # every other off-hue joins the ramp at its deepest step.
    off_hue = [m for m in chromatic_fills if m[3] not in mapping
               and hue_distance(hue(m[3]), dominant) > 45]
    if off_hue:
        def share(rgb):
            return sum(1 for x in chromatic_fills if x[3] == rgb) / max(1, len(chromatic_fills))
        candidates = [m for m in off_hue if share(m[3]) < 0.35]
        if candidates:
            winner = max(candidates, key=lambda m: hue_distance(hue(m[3]), dominant))[3]
            mapping[winner] = LIME
    for m in chromatic_fills:
        if m[3] not in mapping:
            mapping[m[3]] = RAMP[0]

    # 3 neutral fills: shading greys keep order; white/black are ink and ground
    neutral_colors = sorted({m[3] for m in neutral_fills}, key=luma255)
    if neutral_colors:
        n = len(neutral_colors)
        for i, c in enumerate(neutral_colors):
            lum = luma255(c)
            if n == 1:
                mapping[c] = INK if lum > 0.6 and line_art else RAMP[3]
                continue
            # a grey ramp is object shading: keep its order, land it on the ramp
            idx = round(i * 3 / (n - 1))
            mapping[c] = RAMP[3 - idx] if not line_art else (INK if lum > .5 else INK_SOFT)

    # 4 edges. On line art the strokes ARE the drawing, so they take canvas ink.
    # On a solid shape an edge only has to separate two faces, so it is chosen
    # against where those faces actually landed: cold white parts dark faces,
    # ink parts pale ones. Picking it from the SOURCE stroke's lightness is what
    # put faint grey hairlines on pale faces in the first pass.
    face_tokens = [mapping[c] for c in mapping if mapping[c] in RAMP]
    face_depth = (sum(RAMP.index(t) for t in face_tokens) / len(face_tokens)
                  if face_tokens else 1.5)
    separator = COLD_WHITE if face_depth <= 1.6 else INK_SOFT
    for m in strokes:
        if m[3] in mapping and not line_art:
            continue
        if line_art:
            mapping[m[3]] = INK
        elif hue_distance(hue(m[3]), dominant) > 45 and chroma(m[3]) >= 26:
            mapping[m[3]] = LIME
        else:
            mapping[m[3]] = separator
    return mapping, line_art


def recolor(path) -> str | None:
    # The input is a vendored file under assets/shapes/source/, tracked and
    # held by the asset guards; there is no untrusted XML on this path.
    tree = ET.parse(path)  # noqa: S314
    root = tree.getroot()
    marks = collect(root)
    if not marks:
        return None
    mapping, line_art = build_mapping(marks)

    # Surviving labels were white or yellow — legible on the black master and
    # invisible on this one. Text is the one role with no freedom here: it has to
    # be readable against the canvas, so it all becomes canvas ink.
    changed = 0
    for el in root.iter():
        if local(el.tag) in TEXT and parse_color(el.get("fill")):
            el.set("fill", token(INK))
            changed += 1
    for el, attr, _rgb, eff, alpha in marks:
        pair = mapping.get(eff)
        if not pair:
            continue
        el.set(attr, token(pair))
        changed += 1
        if alpha < 1:                      # flattened into the colour already
            for a in (f"{attr}-opacity",):
                if el.get(a):
                    el.set(a, "1")

    # clarity: geometric precision, explicit size, a canvas behind the drawing
    root.set("shape-rendering", "geometricPrecision")
    vb = [float(v) for v in re.findall(r"[-+]?[\d.]+", root.get("viewBox", ""))]
    if len(vb) == 4 and vb[2] > 0:
        ratio = vb[3] / vb[2]
        root.set("width", "1024")
        root.set("height", f"{1024 * ratio:.2f}")
        root.set("preserveAspectRatio", "xMidYMid meet")
    import io
    buf = io.StringIO()
    ET.ElementTree(root).write(buf, xml_declaration=True, encoding="unicode")
    return buf.getvalue()




def regenerate(write: bool) -> tuple[int, list[str]]:
    """-> (units processed, list of files whose regeneration differs from
    what is committed). With write=True the files are rewritten."""
    index = json.loads((SRC / "index.json").read_text(encoding="utf-8"))
    differs: list[str] = []
    done = 0
    for unit in index["units"]:
        src = SRC / unit["file"]
        if not src.exists():
            continue
        target = OUT / unit["file"]
        rendered = recolor(src)
        if rendered is None:
            continue
        done += 1
        current = target.read_text(encoding="utf-8") if target.exists() else None
        if current != rendered:
            differs.append(unit["file"])
            if write:
                target.write_text(rendered, encoding="utf-8")
    return done, differs


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    check = "--check" in argv
    done, differs = regenerate(write=not check)
    if check:
        if differs:
            print(f"FAIL  {len(differs)} of {done} shapes differ from a regeneration "
                  f"out of assets/shapes/source/ with the current tokens — "
                  f"run scripts/build/recolor_shapes.py and commit, or the "
                  f"library is not the tokens' library: "
                  f"{', '.join(differs[:5])}{'…' if len(differs) > 5 else ''}")
            return 1
        print(f"ok    {done} shapes are byte-identical to a regeneration from "
              f"their vendored originals and the current tokens")
        return 0
    print(f"wrote {len(differs)} of {done} shapes (the rest were already current)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
