#!/usr/bin/env python3
"""Publish what every shape in the library actually measures.

**All 206 units carry a NON-ZERO viewBox origin** — measured, not estimated:
133 of them span more than 1000 user units, and their aspect ratios run from
0.13 to 5.32. `p005-2x2-cubed-01` is `viewBox="6542.60 3733.60 12187.80
11277.80"`. SKILL.md already warns that a `<use>` of a non-zero-origin viewBox
renders shifted off frame unless it declares `x`/`y`/`width`/`height` — and the
package published none of the numbers needed to declare them.

`assets/shapes/tags.json` carries a ten-word relation vocabulary and no
geometry at all, so an author placing a label on a shape had two choices: read
the raw SVG (four API calls for eleven shapes on one measured build) or
estimate. One build estimated, and **five figures drew outside their own
viewBox** — `figure_clipped`, and a whole rewrite round.

This emits the numbers instead. Generated, `--check` in CI, the same contract
as `build_card.py` and `build_eval_inventory.py`: a hand-written copy of 206
measurements is the drift class this repository has fixed twenty-six times.

    python3 scripts/build/build_shape_geometry.py            # write it
    python3 scripts/build/build_shape_geometry.py --check    # is it current?
"""
from __future__ import annotations

# --- scripts path bootstrap (canonical; the bootstrap guard enforces this) ---
import pathlib as _bs_pathlib  # noqa: E402
import sys as _bs_sys  # noqa: E402

_SCRIPTS_ROOT = next(p for p in _bs_pathlib.Path(__file__).resolve().parents
                     if p.name == "scripts")
for _sub in ("lib", "render", "check", "build", "ops", ""):
    _p = str(_SCRIPTS_ROOT / _sub) if _sub else str(_SCRIPTS_ROOT)
    if _p not in _bs_sys.path:
        _bs_sys.path.append(_p)
del _bs_pathlib, _bs_sys, _SCRIPTS_ROOT, _sub, _p

import argparse  # noqa: E402
import json  # noqa: E402
import pathlib  # noqa: E402
import re  # noqa: E402
import sys  # noqa: E402

ROOT = next(p for p in pathlib.Path(__file__).resolve().parents
            if (p / "SKILL.md").exists())
SHAPES = ROOT / "assets" / "shapes"
TARGET = SHAPES / "geometry.json"

_VIEWBOX = re.compile(r'viewBox="\s*([-\d.]+)\s+([-\d.]+)\s+([-\d.]+)\s+([-\d.]+)')
_TEXT = re.compile(r"<text\b", re.I)
_PRIM = re.compile(r"<(rect|circle|ellipse|line|path|polyline|polygon)\b", re.I)


def measure(svg: str) -> dict | None:
    m = _VIEWBOX.search(svg)
    if not m:
        return None
    x, y, w, h = (float(v) for v in m.groups())
    return {
        "viewBox": [round(x, 2), round(y, 2), round(w, 2), round(h, 2)],
        # The four attributes a `<use>` must declare to land on frame. Spelled
        # out rather than left as arithmetic on the viewBox, because the
        # arithmetic is exactly what was being got wrong.
        "use": {"x": round(x, 2), "y": round(y, 2),
                "width": round(w, 2), "height": round(h, 2)},
        "aspect": round(w / h, 3) if h else None,
        "texts": len(_TEXT.findall(svg)),
        "primitives": len(_PRIM.findall(svg)),
    }


def build() -> dict:
    units = {}
    for f in sorted(SHAPES.glob("*.svg")):
        g = measure(f.read_text(encoding="utf-8"))
        if g:
            units[f.stem] = g
    return {
        "$comment": (
            "GENERATED by scripts/build/build_shape_geometry.py. Every unit's "
            "viewBox, the four attributes a <use> must declare to render on "
            "frame, its aspect, and how much of it is already text. Read this "
            "instead of opening the SVG: all 206 origins are non-zero, and a "
            "figure composed against an estimated origin draws outside its own "
            "viewBox — which is figure_clipped, and a rebuild round."),
        "schema": 1,
        "units": units,
    }


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true",
                    help="exit 1 when the written manifest is stale")
    a = ap.parse_args(argv)
    want = json.dumps(build(), indent=1, ensure_ascii=False) + "\n"
    if a.check:
        have = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else None
        if have == want:
            print(f"ok    {TARGET.relative_to(ROOT)} is current")
            return 0
        print(f"FAIL  {TARGET.relative_to(ROOT)} is stale — run "
              f"`python3 scripts/build/build_shape_geometry.py`")
        return 1
    TARGET.write_text(want, encoding="utf-8")
    n = len(json.loads(want)["units"])
    print(f"wrote {TARGET.relative_to(ROOT)} ({n} units, {len(want)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
