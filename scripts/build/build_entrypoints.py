#!/usr/bin/env python3
"""Generate every per-platform artifact from one registry and one rule set.

Twelve platforms, and counting. Each one wants an install note; three want a
pointer file at a path their convention dictates; two want a plugin manifest. If
those were hand-written, this repository would be maintaining fifteen more copies
of facts it already holds — and it has already shipped the consequence twice:
`adapters/claude-code.md` told people to `git clone` into the skills directory
while `README.md` insisted on a symlink *because a copy had stranded at an old
version*, and `AGENTS.md` carried a withdrawn fill floor for four releases.

So the derived files are derived. `adapters/platforms.json` holds the platform
facts, `SKILL.md` holds the rules, and everything below is rendered from them.

    python3 scripts/build/build_entrypoints.py            # write
    python3 scripts/build/build_entrypoints.py --check    # verify current (CI)
    python3 scripts/build/build_entrypoints.py --list     # what is generated, and from what

`--check` is the idiom this repo already uses for generated artifacts —
`embed_font.py`, `embed_icons.py`, `build_geography.py` — and it fails with the
same sentence, so a stale tree reports as stale rather than as a mystery.

What this deliberately does NOT generate: `SKILL.md` itself, `AGENTS.md`,
`prompts/lumi-style-core.md`, and anything in `references/`. Those are written by
a person. Assembled prose is worse prose, and the two entry points a reader is
most likely to actually read should be the ones a human composed. The generator
covers the artifacts whose content is *packaging* — paths, invocations, manifests
— where there is no judgement to lose.
"""
from __future__ import annotations

# --- scripts path bootstrap (canonical; the bootstrap guard enforces this) ---
import pathlib as _bs_pathlib  # noqa: E402
import sys as _bs_sys  # noqa: E402

_SCRIPTS_ROOT = next(p for p in _bs_pathlib.Path(__file__).resolve().parents
                     if p.name == "scripts")
for _sub in ("lib", "render", "check", "build", "ops", ""):
    _p = str(_SCRIPTS_ROOT / _sub) if _sub else str(_SCRIPTS_ROOT)
    if _p not in _bs_sys.path:
        _bs_sys.path.append(_p)
del _bs_pathlib, _bs_sys, _SCRIPTS_ROOT, _sub, _p

import argparse  # noqa: E402
import json  # noqa: E402
import pathlib  # noqa: E402
import re  # noqa: E402
import sys  # noqa: E402
from typing import Any  # noqa: E402

import versioning  # noqa: E402 — the one reader of SKILL.md's stamp

ROOT = next(p for p in pathlib.Path(__file__).resolve().parents
            if p.name == "scripts").parent
REGISTRY = ROOT / "adapters" / "platforms.json"
STALE = "is stale or missing; re-run without --check"

BANNER = "<!-- generated by scripts/build/build_entrypoints.py — edit adapters/platforms.json, not this file -->"
JSON_BANNER = "generated by scripts/build/build_entrypoints.py from adapters/platforms.json"


def registry() -> dict:
    return json.loads(REGISTRY.read_text(encoding="utf-8"))


def skill_field(name: str) -> str:
    """One frontmatter scalar from SKILL.md, so the manifests cannot disagree
    with the skill about its own name or description."""
    text = (ROOT / "SKILL.md").read_text(encoding="utf-8")
    body = text.split("---", 2)[1]
    out, capturing = [], False
    for line in body.splitlines():
        if line.startswith(f"{name}:"):
            rest = line.split(":", 1)[1].strip()
            if rest and rest != "|":
                # Fall through to the single emptiness test below. This returned
                # here, so `description: ""` — the exact case the guard was
                # written for — never reached it, and the manifests shipped an
                # empty description with CI fully green.
                out, capturing = [rest.strip('"')], False
                break
            capturing = True
            continue
        if capturing:
            if line and not line.startswith(" "):
                break
            out.append(line.strip())
    value = " ".join(x for x in out if x).strip()
    if not value:
        # Absence is not emptiness. This returned "" for a field it could not
        # find, so renaming `description:` in SKILL.md rendered three manifests
        # with `"description": ""` and `--check` then certified them as current
        # with the same sentence it uses for correct output. `--check` compares
        # the tree against what the generator produces NOW, so it can catch a
        # stale tree and can never catch a generator whose extraction failed.
        # The extraction has to fail loudly instead.
        raise ValueError(
            f"SKILL.md frontmatter has no non-empty {name!r}; the generated "
            f"manifests would ship an empty field and --check would call it current")
    return value


def red_lines_heading() -> str:
    """SKILL.md's red-lines heading, verbatim.

    How MANY there are is whatever SKILL.md says today, never a number written
    here. This function used to match the literal string "## Six non-negotiable",
    so adding a seventh red line crashed every generated pointer file with a bare
    StopIteration - convention 13's problem, in the generator that exists to stop
    prose from counting.
    """
    text = (ROOT / "SKILL.md").read_text(encoding="utf-8")
    m = re.search(r"^## \w+ non-negotiable red lines.*$", text, re.M)
    if not m:
        raise ValueError("SKILL.md has no red-lines heading to lift")
    return m.group(0)


def red_lines() -> str:
    """The red lines, lifted from SKILL.md rather than restated.

    A pointer file that paraphrases them is one more copy waiting to drift; this
    is the one section every platform must carry verbatim.
    """
    text = (ROOT / "SKILL.md").read_text(encoding="utf-8")
    lines = text.splitlines()
    heading = red_lines_heading()
    start = next(i for i, ln in enumerate(lines) if ln == heading)
    end = next((i for i in range(start + 1, len(lines)) if lines[i].startswith("## ")), len(lines))
    block = "\n".join(lines[start + 1:end]).strip()
    if not block:
        # The missing-heading case raised; the EMPTY-section case returned "",
        # so all three pointer files shipped a heading promising six
        # non-negotiable rules with nothing beneath it, every guard green.
        raise ValueError(
            "SKILL.md's red-lines section is empty; the pointer files would each "
            "carry the heading and none of the rules")
    return block


# ── renderers ────────────────────────────────────────────────────────────────

def render_note(p: dict, version: str) -> str:
    paths = p.get("skill_paths") or []
    body = [BANNER, "", f"# Loading in {p['name']}", ""]

    if p["capability"] == "prompt":
        body += [
            f"{p['name']} has no skill mechanism, so it takes the self-contained "
            f"single-file core:", "",
            "1. Open [`prompts/lumi-style-core.md`](../prompts/lumi-style-core.md) "
            "and copy it in full;",
            f"2. {p['invoke']};",
            '3. Then issue tasks normally ("Following the rules above, write…").', "",
            "The core is self-contained with zero tool assumptions; on any conflict, "
            "`references/` wins. Re-copy it after a rule update — it is a snapshot, "
            f"and this one is {version}.",
        ]
    else:
        body += ["```bash", "git clone https://github.com/lumitive/lumi-style ~/src/lumi-style"]
        body += [f"ln -s ~/src/lumi-style {paths[0]}"] if paths else []
        for alt in paths[1:]:
            body.append(f"# or {alt}")
        body += ["```", ""]
        body.append(f"Invoke: {p['invoke']}.")
        body.append("")
        body.append(
            "The skill reads `references/` and `tokens/` on demand — no need to "
            "attach them manually."
        )
        body += ["", "**Symlink rather than copy.** An installed copy silently stranded "
                 "at 0.1.334 while the repo reached 0.1.337, and a deck was built against "
                 "three versions of superseded rules. A symlink cannot go stale."]

    for extra in p.get("extra", []):
        body += ["", extra]

    if p.get("path_verified") is not True:
        body += ["", f"**Unverified install path.** {p.get('path_waiver', '')}"]
    # The tier decides whether this agent may call a deliverable verified, so an
    # unexercised tier claim is published rather than kept in the registry. The
    # install path has been published this way since it had a waiver; the tier
    # had no verification field at all until 0.1.390.
    if p.get("capability_verified") is not True:
        body += ["", f"**Capability tier not exercised.** This note claims the "
                     f"`{p.get('capability')}` tier. {p.get('capability_waiver', '')}"]
    if p.get("docs"):
        body += ["", f"Vendor documentation: {p['docs']}"]
    return "\n".join(body).rstrip() + "\n"


def render_pointer(p: dict, version: str, heading: str, path: str) -> str:
    paths = p.get("skill_paths") or []
    # Every link is relative to the file's own directory, and these files sit at
    # three different depths. The first cut wrote `SKILL.md` from all of them, so
    # .github/copilot-instructions.md pointed at .github/SKILL.md — caught by the
    # markdown-link guard, which is exactly the class of breakage a generator is
    # supposed to make impossible rather than uniform.
    up = "../" * (len(pathlib.PurePosixPath(path).parts) - 1)
    return "\n".join([
        BANNER, "",
        f"# {heading}", "",
        f"> **lumi-style {version}.** This file points at the skill; it does not "
        f"restate it. The rules live in [`SKILL.md`]({up}SKILL.md) and "
        f"[`references/`]({up}references/), and on any conflict those win.", "",
        "You are producing content in LUMI's design language and writing style.",
        "",
        f"**Load [`SKILL.md`]({up}SKILL.md) and follow its workflow.** It reads "
        f"`references/brand.md` first — the only file that says what to reach for — "
        f"then the writing rules, the storyline templates, the design rules with "
        f"`tokens/`, and the eval rubric.",
        "",
        f"**Installed as a skill**, this file is unnecessary: put the repository at "
        f"`{paths[0] if paths else '~/.agents/skills/lumi-style'}` and "
        f"{p['name']} loads it on demand. This file exists for the case where the "
        f"repository is checked out in the working tree instead.",
        "",
        red_lines_heading(),
        "",
        red_lines(),
        "",
        "**Measure rather than trust**: `python3 scripts/check/check_prose.py <file>` for "
        "English prose, `python3 scripts/check/check_design.py <file>` for any HTML, and "
        "`python3 scripts/check/inspect_layout.py <file>` to render the pages and look at "
        "them. Their design judgements gate nothing, but an unmeasurable check "
        "exits 1 and names what it could not find.",
    ]).rstrip() + "\n"


def render_plugin(kind: str, version: str) -> str:
    name, desc = skill_field("name"), skill_field("description")
    doc: dict[str, Any]
    if kind == "plugin":
        doc = {"$comment": JSON_BANNER, "name": name, "version": version,
               "description": desc, "author": {"name": "LUMI"},
               "homepage": "https://github.com/lumitive/lumi-style",
               "repository": {"type": "git",
                              "url": "https://github.com/lumitive/lumi-style"},
               "keywords": ["design-language", "writing-style", "skill",
                            "agent-skills", "lumi"],
               "license": "MIT", "skills": ["./"]}
    elif kind == "marketplace":
        doc = {"$comment": JSON_BANNER, "name": "lumitive",
               "owner": {"name": "LUMI"},
               "plugins": [{"name": name, "source": "./", "description": desc,
                            "version": version}]}
    else:                                                   # .well-known index
        doc = {"$comment": JSON_BANNER, "schema": 1,
               "skills": [{"name": name, "description": desc, "version": version,
                           "path": "/SKILL.md"}]}
    return json.dumps(doc, indent=2, ensure_ascii=False) + "\n"


def targets() -> dict[str, str]:
    """repo-relative path -> the content it must have."""
    data, version = registry(), versioning.skill_version(ROOT)
    out: dict[str, str] = {}
    for p in data["platforms"]:
        out[p["notes_path"]] = render_note(p, version)
    by_id = {p["id"]: p for p in data["platforms"]}
    for pid, path, heading in (
        ("gemini-cli", "GEMINI.md", "LUMI Style — Gemini CLI"),
        ("github-copilot", ".github/copilot-instructions.md", "LUMI Style — GitHub Copilot"),
        ("cursor", ".cursor/rules/lumi-style.mdc", "LUMI Style — Cursor"),
    ):
        if pid in by_id:
            out[path] = render_pointer(by_id[pid], version, heading, path)
    out[".claude-plugin/plugin.json"] = render_plugin("plugin", version)
    out[".claude-plugin/marketplace.json"] = render_plugin("marketplace", version)
    out[".well-known/skills/index.json"] = render_plugin("index", version)
    return out


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--list", action="store_true")
    args = ap.parse_args(argv)

    try:
        wanted = targets()
    except (OSError, ValueError, KeyError, StopIteration) as exc:   # noqa: BLE001
        print(f"could not render entry points: {exc.__class__.__name__}: {exc}")
        return 1

    if args.list:
        for path in sorted(wanted):
            print(f"  {path}")
        print(f"\n{len(wanted)} generated from adapters/platforms.json + SKILL.md")
        return 0

    stale, wrote = [], 0
    for path, content in sorted(wanted.items()):
        target = ROOT / path
        current = target.read_text(encoding="utf-8") if target.exists() else None
        if current == content:
            continue
        if args.check:
            stale.append(path)
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8")
            wrote += 1

    if args.check:
        for path in stale:
            print(f"FAIL  {path} {STALE}")
        if not stale:
            print(f"ok    {len(wanted)} generated entry points are current")
        return 1 if stale else 0
    print(f"wrote {wrote} of {len(wanted)} generated entry points")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
