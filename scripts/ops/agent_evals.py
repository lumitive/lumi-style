#!/usr/bin/env python3
"""Which configuration to run this skill with — measured, never curated.

**The owner asked for the multi-agent evaluation to stop being mixed into the
package's other evals and tools.** This is that tool. `ledger.py` grades
DOCUMENTS; `run_conformance.py` DRIVES agents and stays where it is; this reads
what both of them recorded and orders `agent x model x effort` cells by what
they cost. `conformance/agent-evals.json` declares the axes and the ordering,
and `conformance/README.md` states where the boundary runs.

**Why this is derived rather than a maintained dictionary of models.** The
original request was a weekly-updated table of agents, models and efforts. Four
things make that the wrong shape, and none of them is effort:

  1. `scripts/` is standard library only with no network imports, and the two
     workflows here have no schedule. Nothing in this package can perform a
     weekly search; it would be a human ritual the package could not hold.
  2. One of the twelve registered platforms can enumerate its models read-only
     (`detect --models` reports which, and why the other eleven cannot).
  3. **The decisive one: this package cannot set a model.** All twelve platforms
     load it as a SKILL — an agent is already running, with its model and effort
     already fixed, when it reads `SKILL.md`. There is no code path by which a
     dictionary entry changes a user's session, so a curated table would be
     advice this package could not act on.
  4. `trace_schema` decided `model` stays free text, because model names rot and
     an enum of them is a maintenance tax with no defect behind it. Reversing
     that needs a documented case, and the dictionary has none.

So the answer a user gets is a measurement of runs that actually happened, and
its rows go stale visibly — every one carries `n`, a date, and the skill version
it was measured against.

**What this tool does not do.** It never ratifies, drives, or scores a
deliverable; those belong to the person, to `run_conformance.py`, and to the
checkers. `--check` verifies that the WRITTEN board equals the derivation. It
cannot verify the measurement, which is the same limit `run_conformance
validate` has and is said here in the same words.
"""
import argparse
import collections
import json
import pathlib
import pathlib as _bs_pathlib  # noqa: E402 — the bootstrap's, see below
import statistics
import sys
import sys as _bs_sys  # noqa: E402 — the bootstrap's, see below

# --- scripts path bootstrap (canonical; the bootstrap guard enforces this) ---
_SCRIPTS_ROOT = next(p for p in _bs_pathlib.Path(__file__).resolve().parents
                     if p.name == "scripts")
for _sub in ("lib", "render", "check", "build", "ops", ""):
    _p = str(_SCRIPTS_ROOT / _sub) if _sub else str(_SCRIPTS_ROOT)
    if _p not in _bs_sys.path:
        _bs_sys.path.append(_p)
del _bs_pathlib, _bs_sys, _SCRIPTS_ROOT, _sub, _p

import agent_runs  # noqa: E402
import trace_store  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parents[2]
EVALS = ROOT / "conformance" / "agent-evals.json"
BOARD = ROOT / "conformance" / "CONFIGURATIONS.md"
HISTORY = ROOT / "conformance" / "history.json"

MARK = "<!-- generated by agent_evals.py board -->"
END = "<!-- end generated -->"

# The three answers this tool gives, everywhere it gives one. Two would collapse
# the distinction the whole file exists to keep: an agent nobody has measured
# and an agent that cannot be measured here are different facts, and printing
# them identically is how a board reads as pending work when it is not.
MEASURED, UNMEASURED, UNMEASURABLE = (
    "measured here", "not measured here", "cannot be measured here")


def load_evals() -> dict:
    """The axes register. A hard exit rather than a default: a board rendered
    from a built-in fallback would be a board nobody declared."""
    try:
        return json.loads(EVALS.read_text(encoding="utf-8"))
    except FileNotFoundError:
        sys.exit(f"{EVALS} is missing. It declares what a configuration is "
                 f"scored on; there is no built-in copy of it on purpose.")
    except json.JSONDecodeError as exc:
        sys.exit(f"{EVALS} does not parse (line {exc.lineno}: {exc.msg}).")


def load_history() -> list[dict]:
    if not HISTORY.exists():
        return []
    return json.loads(HISTORY.read_text(encoding="utf-8"))


def earned(history: list[dict]) -> dict[tuple, dict]:
    """-> per (agent, model, effort) what the conformance rounds earned.

    Keyed on the CONFIGURATION, which is why a row needs the `config` key added
    at 0.1.618. The thirty-six rows written before it carry an agent id and
    nothing else, and an agent id is not a configuration: they contribute to no
    cell rather than to a cell called `(agent, None, None)`, because that cell
    would silently pool runs pinned to different models.
    """
    out: dict[tuple, dict] = {}
    for row in history:
        config = row.get("config") or {}
        for task_id, verdict in (row.get("tasks") or {}).items():
            cell_config = config.get(task_id)
            if not cell_config:
                continue
            key = (row["agent"], cell_config.get("model"),
                   cell_config.get("effort"))
            cell = out.setdefault(key, {"earned": 0, "attempted": 0,
                                        "honoured": True, "tasks": set()})
            cell["attempted"] += 1
            cell["tasks"].add(task_id)
            if verdict == "pass":
                cell["earned"] += 1
            asked = cell_config.get("model_asked")
            if asked and cell_config.get("model") and asked not in (
                    cell_config["model"], cell_config["model"].removeprefix(
                        "cursor-")):
                cell["honoured"] = False
    return out


def cells(traces, history) -> list[dict]:
    """-> one row per (agent, model, effort), ordered as the register says.

    Qualification is `agent_runs.board()`'s and is not re-implemented here: one
    quality line, borrowed from `evals/gates.json`, so a thin deck that cannot
    reach the cost board cannot set a median here either.
    """
    by_key: dict[tuple, list] = collections.defaultdict(list)
    admitted = {r["trace_id"]: r for r in agent_runs.board(traces)}
    for t in traces:
        row = admitted.get(t.get("trace_id"))
        if row is None or not t.get("agent"):
            continue
        by_key[(t["agent"], t.get("model"), t.get("effort"))].append((t, row))

    scores = earned(history)
    out = []
    for key, runs in by_key.items():
        agent_id, model, effort = key
        per_page = [r["tokens_per_page"] for _t, r in runs]
        seconds = [r["charged_seconds"] / r["content_pages"] for _t, r in runs
                   if r["charged_seconds"]]
        got = scores.get(key)
        out.append({
            "agent": agent_id, "model": model, "effort": effort,
            "runs": len(runs),
            "tokens_per_page": round(statistics.median(per_page), 1),
            "seconds_per_page": round(statistics.median(seconds), 1)
            if seconds else None,
            "tasks_earned": got["earned"] if got else None,
            "tasks_attempted": got["attempted"] if got else None,
            "effort_honoured": got["honoured"] if got else None,
            "measured": max(t.get("closed_at") or "" for t, _r in runs)[:10],
            "skill_version": max(t.get("skill_version") or "" for t, _r in runs),
        })
    # A cell missing an axis sorts LAST on it rather than being dropped: a
    # dropped cell reads as a cell that scored badly.
    out.sort(key=lambda c: (-(c["tasks_earned"] if c["tasks_earned"] is not None
                              else -1), c["tokens_per_page"]))
    return out


def suggest(agent_id: str, rows: list[dict], registry: list[dict]) -> tuple[str, str]:
    """-> (state, sentence) for one agent. Three states, never two."""
    known = {a["id"]: a for a in registry}
    if agent_id not in known:
        return UNMEASURABLE, (f"{agent_id!r} is not a platform this package "
                              f"claims. adapters/platforms.json is the roster.")
    mine = [r for r in rows if r["agent"] == agent_id]
    if not mine:
        entry = known[agent_id]
        if not entry.get("probe") and not entry.get("drive"):
            return UNMEASURABLE, (
                entry.get("probe_waiver") or "no probe and no driver declared")
        return UNMEASURED, ("installed here or not, no closed trace of this "
                            "agent has cleared the gate line")
    # THE CHEAPEST CELL IS NOT THE ANSWER IF IT NAMES NOTHING TO TYPE. Runs
    # whose model was never recorded pool into a cell whose model reads `—`,
    # and that cell can be the cheapest — claude-code's was, on the first run of
    # this command, and it answered "effort high", which no user can act on. A
    # named cell wins, and the sentence says when a cheaper unnamed one was
    # passed over so the number is not silently improved.
    named = [r for r in mine if r["model"]]
    if not named:
        return UNMEASURED, (
            f"{len(mine)} qualifying run(s), and not one recorded which model "
            f"produced it — a configuration nobody can be told to repeat")
    best = named[0]
    what = " · ".join(x for x in (best["model"], best["effort"]
                                  and f"effort {best['effort']}") if x)
    note = f"{best['runs']} run(s), {best['tokens_per_page']} tokens/page"
    if named[0] is not mine[0]:
        note += (f"; a cheaper cell exists at {mine[0]['tokens_per_page']} and "
                 f"is passed over because it recorded no model")
    # n=1 BEATING n=5 IS SAID OUT LOUD, not corrected. Nothing repeats a run by
    # design, so a single sample cannot separate a flaky agent from a flaky
    # checker — and adding a minimum-n bar to fix it would be inventing a
    # threshold with no documented case behind it, which is what convention 2
    # forbids. Naming the fact is the honest move available.
    deeper = [r for r in named[1:] if r["runs"] > best["runs"]]
    if deeper:
        note += (f"; {deeper[0]['model']} at {deeper[0]['runs']} run(s) is "
                 f"dearer per page and better sampled")
    return MEASURED, f"{what} — {note}"


def render(rows: list[dict], evals: dict) -> str:
    """The board, generated. Every number comes from the rows; nothing here
    reads a clock, or `--check` would go red on the day after it was written.

    **NO HEADER VERSION, and that is a decision.** The first draft stamped the
    checkout's version across the top, and `--check` then failed on every
    release that bumped it — a board going stale because a number changed
    elsewhere, which is GAP-037's shape one file over. Worse, the stamp would
    have claimed a measurement of rules the rows were not measured against.
    Each ROW carries the skill version its runs actually read, which is the
    honest field and the one 0.1.605 exists to insist on.
    """
    lines = [MARK,
             "# LUMI configurations · agent × model × effort",
             "",
             "Generated by `scripts/ops/agent_evals.py board --write` from the "
             "trace store and `conformance/history.json`. **There is no version "
             "stamp on this board on purpose** — each row carries the skill "
             "version its own runs were measured against.",
             "",
             "Ordered by " + ", ".join(evals["ordering"]) +
             ". **This is an ordering by cost among configurations that already "
             "cleared the gate line, not a quality ranking** — above that line "
             "the checks cannot tell two documents apart.",
             "",
             "| agent | model | effort | runs | tokens/page | s/page | earned | "
             "pinned | measured |",
             "|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        earned_cell = ("—" if r["tasks_earned"] is None
                       else f"{r['tasks_earned']} of {r['tasks_attempted']}")
        pinned = {True: "honoured", False: "**not honoured**",
                  None: "—"}[r["effort_honoured"]]
        lines.append(
            f"| {r['agent']} | {r['model'] or '—'} | {r['effort'] or '—'} | "
            f"{r['runs']} | {r['tokens_per_page']} | "
            f"{r['seconds_per_page'] if r['seconds_per_page'] is not None else '—'} | "
            f"{earned_cell} | {pinned} | {r['measured']} · skill "
            f"{r['skill_version']} |")
    if not rows:
        lines.append("| — | — | — | — | — | — | — | — | — |")
        lines.append("")
        lines.append("**No cell has a qualifying run.** That is a statement "
                     "about this store, not about the agents.")
    lines += ["",
              "A dash is an absence, never a zero. `earned` is empty for a cell "
              "whose conformance rounds predate 0.1.618, when a history row "
              "began recording what it was run as; `pinned` is empty for the "
              "same reason.",
              "",
              "**n is small and the board says so rather than smoothing it.** "
              "Nothing repeats a run by design, so a cell with one run cannot "
              "separate a flaky agent from a flaky checker.",
              END]
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(
        description=__doc__.split("\n\n")[0],
        formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("command", choices=["board", "suggest", "plan"],
                    help="board: the configurations table. suggest: one "
                         "agent's measured configuration. plan: which cells "
                         "have no measurement.")
    ap.add_argument("--agent", help="platform id, for `suggest`")
    ap.add_argument("--write", action="store_true",
                    help="with `board`: write conformance/CONFIGURATIONS.md")
    ap.add_argument("--check", action="store_true",
                    help="with `board`: exit 1 if the written board differs "
                         "from the derivation. Verifies the DERIVATION, never "
                         "the measurement.")
    args = ap.parse_args(argv)

    evals = load_evals()
    traces = trace_store.load()
    history = load_history()
    rows = cells(traces, history)
    if args.command == "board":
        text = render(rows, evals)
        # A LABEL, not a path computation. `relative_to` RAISES when the board
        # is somewhere else — a test, an operator's copy — and the one thing
        # this branch must not do is crash while explaining a mismatch.
        where = (str(BOARD.relative_to(ROOT))
                 if BOARD.is_relative_to(ROOT) else str(BOARD))
        if args.check:
            if not BOARD.exists():
                print(f"FAIL  {where} does not exist; "
                      f"`agent_evals.py board --write` writes it")
                return 1
            if BOARD.read_text(encoding="utf-8") != text:
                print(f"FAIL  {where} is not what the traces "
                      f"and history derive. Regenerate with "
                      f"`agent_evals.py board --write`; do not hand-edit it.")
                return 1
            print(f"ok    {where} matches the derivation "
                  f"({len(rows)} cell(s))")
            return 0
        if args.write:
            BOARD.write_text(text, encoding="utf-8")
            print(f"wrote {where} ({len(rows)} cell(s))")
            return 0
        print(text, end="")
        return 0

    registry = json.loads(
        (ROOT / "adapters" / "platforms.json").read_text(encoding="utf-8")
    )["platforms"]

    if args.command == "suggest":
        if not args.agent:
            print("FAIL  suggest needs --agent <platform id>")
            return 1
        state, detail = suggest(args.agent, rows, registry)
        print(f"{args.agent}: {state} — {detail}")
        return 0 if state == MEASURED else 1

    # plan
    measured = {(r["agent"], r["model"], r["effort"]) for r in rows}
    print(f"{len(measured)} measured cell(s) across "
          f"{len({r['agent'] for r in rows})} agent(s).\n")
    for a in registry:
        state, detail = suggest(a["id"], rows, registry)
        print(f"  {a['id']:16} {state:22} {detail}")
    print("\nAxes and triggers: conformance/agent-evals.json. Driving a cell "
          "is `run_conformance.py run --drive`; this tool measures and never "
          "drives.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
