def load_evals() -> dict:
    """The axes register. A hard exit rather than a default: a board rendered
    from a built-in fallback would be a board nobody declared."""
    try:
        return json.loads(EVALS.read_text(encoding="utf-8"))
    except FileNotFoundError:
        sys.exit(f"{EVALS} is missing. It declares what a configuration is "
                 f"scored on; there is no built-in copy of it on purpose.")
    except json.JSONDecodeError as exc:
        sys.exit(f"{EVALS} does not parse (line {exc.lineno}: {exc.msg}).")


def load_history() -> list[dict]:
    """-> the conformance history rows, or a hard exit naming the damage.

    A board scored from a history that did not parse would be a board scored
    from nothing, and the reader keeps absence and damage apart so this can.
    """
    rows, problem = history.read_rows(ROOT)
    if problem:
        raise SystemExit(f"FAIL  {problem}")
    return rows


def earned(history: list[dict]) -> dict[str, dict]:
    """-> per TRACE ID what the conformance rounds earned.

    **Keyed on the trace id, not on the configuration, and the first version of
    this function was keyed on the configuration and could never have matched a
    single row.** The two sides carry different strings for one model: a trace
    records the raw pin (`run_conformance.py` passes `record["model"]` straight
    to `trace.py close`), while `scores.json` records `_model_cell()`'s DISPLAY
    sentence — `cursor-grok-4.6-high (asked cursor-grok-4.6-xhigh)`, or
    `asked deepseek-v4-flash, unconfirmed` when nothing confirmed it. A join on
    those was a join that missed whenever the two differed, which is every
    interesting case, and it would have left `tasks_earned` absent forever
    while GAP-041 named the round that fills it as its closing condition.

    The trace id is a key rather than a string that happens to agree, which is
    what 0.1.617 recorded it for and what four files already said it was.

    Rows written before 0.1.618 carry no `traces` map and contribute nothing —
    not to a cell keyed on the agent alone, which would silently pool runs
    pinned to different models.
    """
    out: dict[str, dict] = {}
    for row in _latest_per_round(history):
        joins = row.get("traces") or {}
        config = row.get("config") or {}
        for task_id, verdict in (row.get("tasks") or {}).items():
            tid = joins.get(task_id) or _sibling_trace(row, task_id)
            if not tid:
                continue
            cell = out.setdefault(tid, {"earned": 0, "attempted": 0,
                                        "honoured": None, "tasks": set()})
            cell["attempted"] += 1
            cell["tasks"].add(task_id)
            if verdict == "pass":
                cell["earned"] += 1
            cell["honoured"] = _honoured(config.get(task_id) or {},
                                         cell["honoured"])
    return out


def _latest_per_round(history: list[dict]) -> list[dict]:
    """-> one row per (agent, run directory) — the last one recorded.

    **`report --record` appends rather than replaces when a round is
    re-driven.** Its idempotence key is `(agent, run_dir, scores_sha256)`, so a
    re-drive into the same directory changes the digest and lands a SECOND row.
    Summing both counts one round twice: a review appended cursor's earlier r17
    row and the board printed `6 of 6` for a three-task round.

    `conformance/history.json` already carries nine duplicate `(agent, run_dir)`
    pairs from before any of this existed. They were harmless while nothing
    joined them to a trace and they are not harmless now.

    The LAST row wins, because `--record` appends and a re-drive supersedes what
    it re-drove. Rows with no `run_dir` — none today — are each their own round
    rather than colliding on `None`.
    """
    latest: dict[tuple, dict] = {}
    order: list[tuple] = []
    for i, row in enumerate(history):
        key = (row.get("agent"), row.get("run_dir") or f"#{i}")
        if key not in latest:
            order.append(key)
        latest[key] = row
    return [latest[k] for k in order]


def _sibling_trace(row: dict, task_id: str) -> str | None:
    """-> the trace of a task run at the SAME PINS in the same round, if one is.

    **Most tasks open no trace at all.** `trace.py` opens one for a build, and
    only the deck task declares a storyline — the harness prints "no trace: the
    task declares no storyline" for the other two. So a join on the trace id
    alone can never count more than one task per round, and `tasks_earned`
    would have read `1 of 1` for an agent that earned three.

    A history row is ONE round of ONE agent, so two of its tasks carrying the
    same pins were **asked for** the same configuration. That is the claim, and
    the first draft of this docstring said "were the same configuration by
    construction" — which the row it was written for contradicts: cursor's r17
    round pinned all three tasks to `cursor-grok-4.6-high` and the CLI answered
    `Cursor Grok 4.6 High` twice and `Cursor Grok 4.6` once. The pins are the
    operator's intent and a configuration is what was asked for, so the join
    stands; what does not stand is calling the answers identical.

    **The disagreement is not swallowed — it is spent on `effort_honoured`.**
    Every joined task's own `model_ran` goes through `_honoured`, so a task that
    announced something the pin does not cover leaves the cell unconfirmed
    rather than silently inheriting its sibling's confirmation.

    The comparison is on `model_asked` and `effort` — never the CLI's answer,
    which is a display sentence and comparing those is the defect 0.1.623 fixed.
    A task with no pins recorded matches nothing, rather than matching every
    other unpinned task in the row.

    Only the deck task declares a storyline today, so `joins` never holds more
    than one entry. If a second task ever opens a trace, which sibling a task
    borrows becomes insertion-order dependent — noted rather than guarded,
    because a rule for choosing between two traces of one round needs a round
    that has two.
    """
    config = row.get("config") or {}
    joins = row.get("traces") or {}
    # THE CELL, not a hand-built pin pair (0.1.643). `cell_of_config` reads
    # `model_asked` rather than `model` for the reason stated above, and it is
    # now the only place that rule lives; a task with nothing pinned yields
    # None here and matches nothing, which is what the pair did by `all(pins)`.
    agent_id = row.get("agent") or "?"
    mine = agent_cell.cell_of_config(agent_id, config.get(task_id))
    if mine is None:
        return None
    for other, tid in joins.items():
        if agent_cell.cell_of_config(agent_id, config.get(other)) == mine:
            return tid
    return None


def _honoured(cell_config: dict, so_far) -> bool | None:
    """-> did the run announce the model that was asked for?

    THREE ANSWERS, folded over a cell's tasks. `None` when nothing was pinned,
    nothing recorded the pin, or the two names are merely COMPATIBLE — an
    unpinned run cannot dishonour a pin, and calling that `True` would let
    "nobody asked for anything" wear the same word as "the CLI did what it was
    told". Once any task says `False` the cell stays `False`.

    The comparison is against `model_ran`, the raw id the CLI announced, and
    never against `model`, which in a score cell is a display sentence built for
    a board column. It also no longer FALLS BACK to `model` when `model_ran` is
    absent: the fallback compared a pin to that sentence, and a sentence
    beginning with the answer would have read as confirmation of it.
    """
    if so_far is False:
        return False
    verdict = agent_capability.same_model(cell_config.get("model_asked"),
                                          cell_config.get("model_ran"))
    if verdict is None:
        # NO EVIDENCE DOES NOT OVERWRITE EVIDENCE. A task whose pin and answer
        # are merely compatible leaves the cell where it was; it neither
        # confirms nor spends the confirmation another task already gave.
        return so_far
    return verdict if verdict is False else (so_far is not False)


REVIEWS = ROOT / "reviews" / "scores.json"


def reader_scores(traces) -> dict[str, float]:
    """-> per TRACE ID the median of a human reader's C1–C8 scores.

    **The axis the board could not have.** `conformance/agent-evals.json` has said since it
    was written that above the gate line the checks cannot tell two documents
    apart, and 0.1.627 measured what that costs: twelve decks, four tiers,
    every one passing every gate, and the owner reading all twelve reported the
    cheapest tier as the WORST. Ordering on cost alone recommends it.

    A human read is the only evidence that separates them, and one already
    exists in `reviews/scores.json` — it was simply keyed to a document and
    never to a configuration. The join is `corpus_id`, present on both sides.

    THE READER'S SCORES, NOT THE AGENT'S SELF-SCORES. A record carries both;
    `self` is the producer grading its own work, which is the one input a
    quality axis must not take. Median rather than mean over C1–C8: a single 1
    on one dimension should not swamp seven 4s, and a single 4 should not
    rescue seven 1s.

    Absent dimensions are skipped, not counted as zero — a reader who did not
    score C2 has not scored it badly.
    """
    if not REVIEWS.exists():
        return {}
    doc = json.loads(REVIEWS.read_text(encoding="utf-8"))
    by_corpus: dict[str, list[float]] = {}
    for review in doc.get("reviews") or []:
        cid = review.get("corpus_id")
        marks = [v for v in (review.get("reader") or {}).values()
                 if isinstance(v, (int, float)) and not isinstance(v, bool)]
        if cid and marks:
            by_corpus.setdefault(cid, []).extend(marks)
    return {t["trace_id"]: statistics.median(by_corpus[t["corpus_id"]])
            for t in traces
            if t.get("corpus_id") in by_corpus and t.get("trace_id")}


def cells(traces, history) -> list[dict]:
    """-> one row per (agent, model, effort, SKILL VERSION).

    **The skill version and the CLI build are part of the key, and leaving
    either out hides a real distortion.** The first version grouped without it and printed
    `max()` of the versions it had pooled, so one row could average runs
    measured under three different rulers and name only the newest. Measured on
    the cell this was found in: cursor at `cursor-grok-4.6-high` read 6290
    tokens per page over seven runs spanning 0.1.542 to 0.1.623, and 7093 over
    the two that actually ran under 0.1.623 — **12.8% of the headline number
    was the ruler, not the agent.** That is the misattribution 0.1.605 exists
    to describe, one file over.

    It also makes the board answer a question it could not: whether a release
    made a configuration cheaper or dearer. A pooled cell cannot.

    The CLI build joined the key at 0.1.626 for the same reason one axis over:
    two rounds of one configuration a week apart ran under
    `2026.08.11-e8db854` and `2026.08.25-3e8eec8`, and a difference between
    them had a cause nothing recorded. A trace written before the field exists
    carries `None`, which is its own cell rather than being folded into a
    named one — "we did not record it" is not the same run as "we did".

    Qualification is `agent_runs.board()`'s and is not re-implemented here: one
    quality line, borrowed from `evals/gates.json`, so a thin deck that cannot
    reach the cost board cannot set a median here either.

    **`output_tokens` is reported beside `tokens_per_page` and is the steadier
    of the two.** Measured over four repeats of one configuration: output
    tokens spread 16.5%, content pages 12.5%, and the ratio of them 32.3% —
    dividing a steady numerator by a moving denominator compounds both. Pages
    are what the agent chose to write, which is a fact about the output rather
    than noise to divide away, so both are printed and neither is hidden.
    """
    by_key: dict[tuple, list] = collections.defaultdict(list)
    admitted = {r["trace_id"]: r for r in agent_runs.board(traces)}
    for t in traces:
        row = admitted.get(t.get("trace_id"))
        if row is None or not t.get("agent"):
            continue
        # THE POOLED KEY IS A TYPE NOW (0.1.643). The 5-tuple was built here by
        # hand, projected back to three members two hundred lines down, and
        # built as two members with the agent dropped in `agent_runs.matrix` —
        # one concept, three shapes, no shared constructor. `Measured` carries
        # the cell and the ruler as separate values and hands back this exact
        # tuple, in this order; the normalization that used to live in the
        # comment below now lives in the constructor, for every reader.
        #
        # (What the comment said, kept because it is the reason: `close
        # --cli-version ""` stores `""`, the schema type-checks the field and
        # nothing else, and `render` prints `""` and `None` alike as a dash — so
        # one configuration rendered as two identical-looking rows with two
        # medians.)
        by_key[agent_cell.measured_of_trace(t).pooled_key()].append((t, row))

    scored = earned(history)
    read = reader_scores(traces)
    out = []
    for key, runs in by_key.items():
        agent_id, model, effort, version, cli = key
        per_page = [r["tokens_per_page"] for _t, r in runs]
        out_tokens = [r["output_tokens"] for _t, r in runs
                      if r["output_tokens"] is not None]
        pages = [r["content_pages"] for _t, r in runs]
        seconds = [r["charged_seconds"] / r["content_pages"] for _t, r in runs
                   if r["charged_seconds"]]
        # Summed over the cell's OWN traces, by id. A cell is a set of runs and
        # each run either has a history row or does not; adding them is the
        # whole of the join now that its key is stable.
        mine = [scored[t["trace_id"]] for t, _r in runs
                if t["trace_id"] in scored]
        honoured = [m["honoured"] for m in mine if m["honoured"] is not None]
        marks = [read[t["trace_id"]] for t, _r in runs if t["trace_id"] in read]
        out.append({
            "agent": agent_id, "model": model, "effort": effort,
            "runs": len(runs),
            "tokens_per_page": round(statistics.median(per_page), 1),
            "seconds_per_page": round(statistics.median(seconds), 1)
            if seconds else None,
            "reader_score": round(statistics.median(marks), 1) if marks else None,
            "reader_reads": len(marks),
            "tasks_earned": sum(m["earned"] for m in mine) if mine else None,
            "tasks_attempted": sum(m["attempted"] for m in mine) if mine else None,
            "effort_honoured": all(honoured) if honoured else None,
            "measured": max(t.get("closed_at") or "" for t, _r in runs)[:10],
            "skill_version": version,
            "cli_version": cli,
            # THE SPREAD, NOT ONLY THE MIDDLE. A median with no range beside it
            # invites a reader to order two cells that overlap completely.
            # Measured on repeats of ONE configuration: charged seconds spread
            # 99.4% across four runs, which is a number that can order nothing,
            # and it had been printing as a single value like the rest.
            "output_tokens": round(statistics.median(out_tokens))
            if out_tokens else None,
            "output_tokens_range": (min(out_tokens), max(out_tokens))
            if out_tokens else None,
            "tokens_per_page_range": (round(min(per_page), 1),
                                      round(max(per_page), 1)),
            "seconds_per_page_range": (round(min(seconds), 1),
                                       round(max(seconds), 1))
            if seconds else None,
            "content_pages_range": (min(pages), max(pages)),
        })
    # A cell missing an axis sorts LAST on it rather than being dropped: a
    # dropped cell reads as a cell that scored badly.
    out.sort(key=_ordering)
    return out


def _ordering(cell: dict) -> tuple:
    """The register's ordering, as one function both readers call.

    `reader_score desc, tasks_earned desc, tokens_per_page asc`.

    **A HUMAN READ OUTRANKS BOTH, and 0.1.627 is why.** Twelve decks, four
    reasoning tiers, every one passing every gating check — and the owner
    reading all twelve reported the CHEAPEST tier as the worst, its weakness
    entirely in the figures. A board ordered on cost recommends exactly that
    tier. The register has said since it was written that above the gate line
    the checks cannot tell two documents apart; this is the axis that can, and
    it sits first because a measurement of the thing itself outranks a proxy
    for it.

    No cell carries one today — the two reviewed builds recorded no output
    tokens, so neither reaches the cost board at all. The rule is written now
    rather than when the first score arrives, so that nobody has to argue about
    precedence with a number already on the table.

    A cell missing an axis sorts LAST on it rather than being dropped, which is
    the same convention the other two follow.
    """
    read = cell.get("reader_score")
    earned_ = cell["tasks_earned"]
    return (-(read if read is not None else -1),
            -(earned_ if earned_ is not None else -1),
            cell["tokens_per_page"])


def pick(agent_id: str, rows: list[dict],
         registry: list[dict]) -> tuple[str, dict | None, list[str]]:
    """-> (state, the cell to recommend or None, the caveats about it).

    **One selection rule, and both readers call it.** The README generator had a
    second copy: it threw `suggest()`'s answer away, recomputed the pick, and
    printed neither caveat — so the file whose whole point is reaching the user
    was the one place the two things the tool exists to say went unsaid. A
    review found it. A duplicated selection rule is the defect this repository
    spends most of its releases on, and it had grown one inside the release that
    forbade it.
    """
    known = {a["id"]: a for a in registry}
    if agent_id not in known:
        return UNMEASURABLE, None, [
            f"{agent_id!r} is not a platform this package claims. "
            f"adapters/platforms.json is the roster."]
    # SORTED HERE, not assumed. `pick` reads `mine[0]` as "the cheapest" and
    # `named[0]` as "the cheapest that names a model", which is only true if
    # the caller happened to have sorted — `cells()` does, and a test calling
    # `pick` directly did not, which is how a planted red failed to plant. A
    # function whose correctness depends on its caller's habits is a function
    # that will be called wrongly.
    mine = sorted((r for r in rows if r["agent"] == agent_id),
                  key=_ordering)
    if not mine:
        entry = known[agent_id]
        if not entry.get("probe") and not entry.get("drive"):
            return UNMEASURABLE, None, [
                entry.get("probe_waiver") or "no probe and no driver declared"]
        return UNMEASURED, None, [
            "installed here or not, no closed trace of this agent has cleared "
            "the gate line"]
    # THE CHEAPEST CELL IS NOT THE ANSWER IF IT NAMES NOTHING TO TYPE. Runs
    # whose model was never recorded pool into a cell whose model reads `—`,
    # and that cell can be the cheapest — claude-code's was, on the first run of
    # this command, and it answered "effort high", which no user can act on. A
    # named cell wins, and a caveat says when a cheaper unnamed one was passed
    # over so the number is not silently improved.
    named = [r for r in mine if r["model"]]
    if not named:
        return UNMEASURED, None, [
            f"{len(mine)} qualifying run(s), and not one recorded which model "
            f"produced it — a configuration nobody can be told to repeat"]
    # ONE RULER. Cells carry their skill version since 0.1.626, so an agent now
    # has one cell per configuration PER RELEASE — and an older cell is not an
    # alternative a reader can choose. Recommending it, or citing it as "dearer
    # and better sampled" the way the first version did, offers a measurement of
    # rules that no longer exist. The newest release with a named cell wins, and
    # the row already prints which one it is.
    # `versioning.sort_key`, NOT a bare `max()` over strings: `0.1.99` outranks
    # `0.1.100` lexicographically, and every patch number in the store is three
    # digits today, so nothing would look wrong until the thousandth release.
    # The comparator was a private copy here until 0.1.635, beside a second copy
    # in the driver — with a comment arguing correctly against importing the
    # DRIVER, which is an argument for a shared home rather than for a copy.
    newest = max((r["skill_version"] or "" for r in named), key=versioning.sort_key)
    named = [r for r in named if (r["skill_version"] or "") == newest]
    # EVERYTHING below compares within one release. `mine` spans all of them,
    # and a caveat pointing at another release's cell offers an alternative
    # nobody can pick.
    mine = [r for r in mine if (r["skill_version"] or "") == newest]
    best = named[0]
    caveats = []
    if named[0] is not mine[0]:
        caveats.append(
            f"a cheaper cell exists at {mine[0]['tokens_per_page']} tokens/page "
            f"and is passed over because it recorded no model")
    # n=1 BEATING n=5 IS SAID OUT LOUD as well as barred. Until 0.1.648 this
    # comment argued AGAINST a minimum-n bar — "inventing a threshold with no
    # documented case behind it" — and that was right when it was written and
    # is not now: the owner ruled one (MIN_RUNS_TO_RECOMMEND) with a case, and
    # a comment left arguing against the code beside it is the drift this
    # repository spends most of its releases on.
    # Same ruler only — `named` was already narrowed to the newest release.
    deeper = [r for r in named[1:] if r["runs"] > best["runs"]]
    if deeper:
        caveats.append(
            f"{describe(deeper[0])} at {deeper[0]['runs']} run(s) is dearer "
            f"per page and better sampled")
    # THE FLOOR IS ON THE RECOMMENDATION, NOT ON THE ROW. The cell and its
    # numbers are still returned — hiding them would answer "not measured",
    # which is false and is the two-answers-where-there-are-three mistake this
    # file makes elsewhere. What changes is the STATE: a caller asking "what
    # should I configure" is told this is not yet an answer.
    if best["runs"] < MIN_RUNS_TO_RECOMMEND:
        caveats.insert(0, (
            f"{best['runs']} run(s) at skill {best['skill_version']}; "
            f"{MIN_RUNS_TO_RECOMMEND} are needed before a configuration is "
            f"recommended, and a round is driven only at a large version step, "
            f"so the three are driven together or not at all"))
        return UNDERSAMPLED, best, caveats
    return MEASURED, best, caveats


def describe(cell: dict) -> str:
    """-> the configuration as a person would type it.

    Model AND effort. Printing the model alone made a caveat name the winning
    cell's own model — `cursor-grok-4.6-high at 5 run(s) is dearer than
    cursor-grok-4.6-high`, which is two cells differing only by effort
    rendering as self-contradiction.
    """
    return " · ".join(x for x in (
        cell["model"], cell["effort"] and f"effort {cell['effort']}") if x)


def suggest(agent_id: str, rows: list[dict], registry: list[dict]) -> tuple[str, str]:
    """-> (state, sentence) for one agent. Three states, never two."""
    state, best, caveats = pick(agent_id, rows, registry)
    if best is None:
        return state, caveats[0]
    head = f"{best['runs']} run(s)"
    if best.get("output_tokens") is not None:
        head += f", {best['output_tokens']:,} output tokens"
    head += (f", {best['tokens_per_page']}/page, measured against skill "
             f"{best['skill_version']}")
    return state, f"{describe(best)} — {'; '.join([head, *caveats])}"


def render(rows: list[dict], evals: dict) -> str:
    """The board, generated. Every number comes from the rows; nothing here
    reads a clock, or `--check` would go red on the day after it was written.

    **NO HEADER VERSION, and that is a decision.** The first draft stamped the
    checkout's version across the top, and `--check` then failed on every
    release that bumped it — a board going stale because a number changed
    elsewhere, which is GAP-037's shape one file over. Worse, the stamp would
    have claimed a measurement of rules the rows were not measured against.
    Each ROW carries the skill version its runs actually read, which is the
    honest field and the one 0.1.605 exists to insist on.
    """
    lines = [MARK,
             "# LUMI configurations · agent × model × effort",
             "",
             "Generated by `scripts/ops/agent_evals.py board --write` from the "
             "trace store and `conformance/history.json`. **There is no version "
             "stamp on this board on purpose** — each row carries the skill "
             "version its own runs were measured against.",
             "",
             "Ordered by " + ", ".join(evals["ordering"]) +
             ". **Below the read, this remains an ordering by COST among "
             "configurations that already cleared the gate line, not a quality "
             "ranking** — the checks cannot tell two documents apart up there, "
             "which is exactly why a human read LEADS the sort and a cell "
             "without one falls back to cost. The sentence said `by cost` flat "
             "until a review read it against the ordering it interpolates, and "
             "then said `above the read`, which is where nothing sits.",
             "",
             "| agent | model | effort | skill | cli | n | read | "
             "output tokens | tokens/page | s/page | pages | earned | pinned | "
             "measured |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]

    def span(middle, rng, fmt="{:,.0f}"):
        """-> `median (min–max)`, or the median alone when n is 1.

        A median with no range beside it invites a reader to order two cells
        that overlap completely. Measured over four repeats of ONE
        configuration: charged seconds spread 99.4%.
        """
        if middle is None:
            return "—"
        lo, hi = rng or (middle, middle)
        if lo == hi:
            return fmt.format(middle)
        return f"{fmt.format(middle)} ({fmt.format(lo)}–{fmt.format(hi)})"

    for r in rows:
        earned_cell = ("—" if r["tasks_earned"] is None
                       else f"{r['tasks_earned']} of {r['tasks_attempted']}")
        pinned = {True: "honoured", False: "**not honoured**",
                  None: "—"}[r["effort_honoured"]]
        pages_lo, pages_hi = r["content_pages_range"]
        lines.append(
            f"| {r['agent']} | {r['model'] or '—'} | {r['effort'] or '—'} | "
            f"{r['skill_version'] or '—'} | {r.get('cli_version') or '—'} | "
            f"{r['runs']} | "
            + (f"**{r['reader_score']}** (n={r['reader_reads']}) | "
               if r.get("reader_score") is not None else "— | ")
            + f"{span(r['output_tokens'], r['output_tokens_range'])} | "
            f"{span(r['tokens_per_page'], r['tokens_per_page_range'])} | "
            f"{span(r['seconds_per_page'], r['seconds_per_page_range'], '{:,.1f}')} | "
            f"{pages_lo if pages_lo == pages_hi else f'{pages_lo}–{pages_hi}'} | "
            f"{earned_cell} | {pinned} | {r['measured']} |")
    if not rows:
        lines.append("| — | — | — | — | — | — | — | — | — | — | — | — | — | — |")
        lines.append("")
        lines.append("**No cell has a qualifying run.** That is a statement "
                     "about this store, not about the agents.")
    lines += ["",
              "**`read` is a human's median C1–C8 score, and it orders "
              "everything else.** Above the gate line the checks cannot tell "
              "two documents apart — measured at 0.1.627, where twelve decks "
              "across four reasoning tiers all passed every gate and the "
              "cheapest tier was, on reading, the worst. A dash means nobody "
              "has read that configuration's output, not that it read badly. "
              "The reader's scores are used and the agent's self-scores are "
              "not: a producer grading its own work is the one input a quality "
              "axis must refuse.",
              "",
              "**`output tokens` is the reference number, and `tokens/page` is "
              "the same measurement divided by a moving denominator.** Over "
              "four repeats of one configuration, output tokens spread 16.5%, "
              "content pages 12.5%, and the ratio of the two 32.3% — the "
              "division compounds both. Pages are what the agent chose to "
              "write, so they are a column rather than a divisor.",
              "",
              "**`s/page` orders nothing.** The same four repeats spread it "
              "124.0% — the row two above says so itself, 95.2 to 258.6 around "
              "a median of 131.8. (This sentence said 99.4% until 0.1.628, "
              "which is the spread of the RAW charged seconds; dividing them "
              "by a page count the agent chose made it worse, not better, and "
              "the table the sentence sits under could be used to check it.) "
              "It measures server load and retries, not the "
              "configuration. It is printed because a run's duration is a real "
              "cost to whoever waits for it, and with its range so that nobody "
              "reads a middle value as a ranking.",
              "",
              "**The skill version AND the CLI build are part of a cell's "
              "identity.** A cell pooling runs from several releases would "
              "average three rulers and name one: measured on "
              "`cursor-grok-4.6-high`, 12.8% of the headline number was the "
              "ruler rather than the agent. The CLI updates on its own "
              "schedule — two rounds of one configuration a week apart ran "
              "under different builds — so it is a column rather than a "
              "footnote. A dash there means the run predates the field.",
              "",
              "A dash is an absence, never a zero. `earned` is empty for a cell "
              "whose conformance rounds predate 0.1.618, when a history row "
              "began recording what it was run as; `pinned` is empty for the "
              "same reason.",
              "",
              "**n is small and the board says so rather than smoothing it.** "
              "Nothing repeats a run by design, so a cell with one run cannot "
              "separate a flaky agent from a flaky checker.",
              END]
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(
        description=__doc__.split("\n\n")[0],
        formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("command", choices=["board", "suggest", "plan"],
                    help="board: the configurations table. suggest: one "
                         "agent's measured configuration. plan: which cells "
                         "have no measurement.")
    ap.add_argument("--agent", help="platform id, for `suggest`")
    ap.add_argument("--write", action="store_true",
                    help="with `board`: write conformance/CONFIGURATIONS.md")
    ap.add_argument("--check", action="store_true",
                    help="with `board`: exit 1 if the written board differs "
                         "from the derivation. Verifies the DERIVATION, never "
                         "the measurement.")
    args = ap.parse_args(argv)

    evals = load_evals()
    traces = trace_store.load()
    history = load_history()
    rows = cells(traces, history)
    if args.command == "board":
        text = render(rows, evals)
        # A LABEL, not a path computation. `relative_to` RAISES when the board
        # is somewhere else — a test, an operator's copy — and the one thing
        # this branch must not do is crash while explaining a mismatch.
        where = (str(BOARD.relative_to(ROOT))
                 if BOARD.is_relative_to(ROOT) else str(BOARD))
        if args.check:
            if not BOARD.exists():
                print(f"FAIL  {where} does not exist; "
                      f"`agent_evals.py board --write` writes it")
                return 1
            if BOARD.read_text(encoding="utf-8") != text:
                print(f"FAIL  {where} is not what the traces "
                      f"and history derive. Regenerate with "
                      f"`agent_evals.py board --write`; do not hand-edit it.")
                return 1
            print(f"ok    {where} matches the derivation "
                  f"({len(rows)} cell(s))")
            return 0
        if args.write:
            BOARD.write_text(text, encoding="utf-8")
            print(f"wrote {where} ({len(rows)} cell(s))")
            return 0
        print(text, end="")
        return 0

    registry = platform_registry.platforms(ROOT)

    if args.command == "suggest":
        if not args.agent:
            print("FAIL  suggest needs --agent <platform id>")
            return 1
        state, detail = suggest(args.agent, rows, registry)
        print(f"{args.agent}: {state} — {detail}")
        return 0 if state == MEASURED else 1

    # plan
    measured = {agent_cell.cell(r["agent"], r["model"], r["effort"]).key()
                for r in rows}
    print(f"{len(measured)} measured cell(s) across "
          f"{len({r['agent'] for r in rows})} agent(s).\n")
    for a in registry:
        state, detail = suggest(a["id"], rows, registry)
        print(f"  {a['id']:16} {state:22} {detail}")
    # HUMAN READS THAT CANNOT REACH A CELL. A read is the axis that orders
    # everything else, and it is worthless if it cannot be attached — so the
    # ones that exist and land nowhere are the actionable line here, not a
    # footnote. Today both do: the two reviewed builds recorded no output
    # tokens, so `board()` admits neither and neither becomes a cell at all.
    read = reader_scores(trace_store.load())
    placed = sum(1 for r in rows if r.get("reader_score") is not None)
    print()
    if not read:
        print("  no human read is joined to any trace. `reviews/scores.json` "
              "joins by `corpus_id`; a review without one, or a build whose "
              "trace never recorded one, reaches no configuration.")
    else:
        print(f"  {len(read)} human read(s) joined to a trace, {placed} of "
              f"them on a cell.")
        if placed < len(read):
            print(f"  {len(read) - placed} read(s) reach no cell: the trace is "
                  f"not on the cost board — unclosed, no gates recorded, or no "
                  f"output tokens — so there is no configuration to attach the "
                  f"score to. A reviewed build needs a usage file at close.")

    # WHAT THE RECORDED VOCABULARIES SAY. The `vocabulary-changed` trigger was
    # declared with nothing storing a vocabulary to compare against (GAP-042);
    # `detect --ask-models --record` writes one now, and this is where a person
    # sees whether the set an agent offers has moved under a measurement.
    recorded, vocab_problem = agent_capability.recorded_vocabularies(ROOT)
    print()
    if vocab_problem:
        # NAMED, not swallowed: a damaged store and a store nobody has written
        # are different answers, and this line is where a reader learns which.
        print(f"  {vocab_problem}")
    elif not recorded:
        print("  no vocabulary recorded yet — `run_conformance.py detect "
              "--ask-models --record` writes one, and until then the "
              "`vocabulary-changed` trigger has nothing to compare against.")
    else:
        for aid in sorted(recorded):
            # THROUGH `offered()`, not by re-deriving the field. This read
            # `entry.get("ids") or []`, which is the validation that function
            # exists to do: a string id set counted its CHARACTERS as models,
            # and an entry with no `ids` printed "offers 0" — indistinguishable
            # from a probe that found nothing.
            ids, problem = agent_capability.offered(aid, ROOT)
            if problem:
                print(f"  {aid:16} {problem}")
                continue
            offered = set(ids or [])
            used = {r["model"] for r in rows
                    if r["agent"] == aid and r["model"]}
            # A MODEL MEASURED THAT THE CLI NO LONGER OFFERS is the thing worth
            # printing: it means a recommendation on this board names something
            # a reader cannot select any more.
            retired = sorted(m for m in used if m not in offered)
            print(f"  {aid:16} offers {len(offered):>3} model(s), "
                  f"{len(used)} measured"
                  + (f" — RETIRED: {', '.join(retired)}" if retired else "")
                  + f"  (asked {recorded[aid].get('asked_on', '?')})")
    print("\nAxes and triggers: conformance/agent-evals.json. Driving a cell "
          "is `run_conformance.py run --drive`; this tool measures and never "
          "drives.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
